// Only needed for the local web dev-preview convenience: expo-sqlite's web
// backend (wa-sqlite) ships a .wasm file and needs cross-origin isolation
// headers. Android (the shipped target) uses native SQLite and isn't
// affected by any of this.
const { getDefaultConfig } = require('expo/metro-config');

/** @type {import('expo/metro-config').MetroConfig} */
const config = getDefaultConfig(__dirname);

config.resolver.assetExts.push('wasm');

config.server.enhanceMiddleware = (middleware) => {
  return (req, res, next) => {
    res.setHeader('Cross-Origin-Opener-Policy', 'same-origin');
    res.setHeader('Cross-Origin-Embedder-Policy', 'require-corp');
    return middleware(req, res, next);
  };
};

module.exports = config;
